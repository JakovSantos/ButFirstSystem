-- =====================================================================
--  BUT FIRST, SYSTEM - Oracle DDL for Oracle SQL Developer Data Modeler
--  Same four tables, keys and rules as database/schema.sql (MySQL),
--  written in Oracle syntax so Data Modeler can import it:
--
--    File > Import > DDL File > choose this file > Database: Oracle Database 12c (or later)
--    -> creates the RELATIONAL model
--    Relational model toolbar: "Engineer to Logical Model" (double arrow, <<)
--    -> creates the LOGICAL model (entities, attributes, relationships)
--    Logical diagram: right-click the canvas > Notation > Barker Notation
--
--  Relationships (from the foreign keys):
--    PAYROLL 1 ---- 0..* EMPLOYEE_SHIFT   (a payroll employee may have shifts; a shift may belong to one employee)
--    PAYROLL 1 ---- 0..1 USERS            (an employee has at most one login; an admin login has no employee)
--    INVENTORY is independent.
--  Oracle has no ON UPDATE CASCADE, so that MySQL option is left out; ON DELETE rules are kept.
-- =====================================================================

CREATE TABLE inventory (
    product_id    NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    product_name  VARCHAR2(100)  NOT NULL,
    category      VARCHAR2(50)   NOT NULL,
    price         NUMBER(10,2)   NOT NULL,
    quantity      NUMBER(10)     DEFAULT 0 NOT NULL,
    supplier      VARCHAR2(100),
    date_added    DATE           NOT NULL,
    image_path    VARCHAR2(255),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT inventory_pk PRIMARY KEY (product_id),
    CONSTRAINT inventory_price_ck CHECK (price >= 0),
    CONSTRAINT inventory_quantity_ck CHECK (quantity BETWEEN 0 AND 1000),
    CONSTRAINT inventory_category_ck CHECK (category IN ('SUPPLIES', 'DAIRY', 'SYRUPS', 'COFFEE', 'TEA', 'SWEETENERS',
        'TOPPINGS', 'INGREDIENTS', 'FOODS', 'CROISSANT', 'MERCHANDISE', 'CAKES', 'COOKIES BROWNIES', 'BEVERAGES'))
);

CREATE INDEX inventory_category_idx ON inventory (category);

CREATE TABLE payroll (
    id                  NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    employee_id         VARCHAR2(50)   NOT NULL,
    name                VARCHAR2(100)  NOT NULL,
    daily_rate          NUMBER(10,2)   DEFAULT 550 NOT NULL,
    days_worked         NUMBER(3)      DEFAULT 0 NOT NULL,
    ot_hours            NUMBER(3)      DEFAULT 0 NOT NULL,
    late_hours          NUMBER(3)      DEFAULT 0 NOT NULL,
    deduction_per_hour  NUMBER(10,2)   DEFAULT 0 NOT NULL,
    holiday_present     NUMBER(3)      DEFAULT 0 NOT NULL,
    holiday_type        VARCHAR2(50),
    net_pay             NUMBER(10,2)   DEFAULT 0 NOT NULL,
    gross_pay           NUMBER(10,2)   DEFAULT 0 NOT NULL,
    total_deductions    NUMBER(10,2)   DEFAULT 0 NOT NULL,
    sss                 NUMBER(10,2)   DEFAULT 0 NOT NULL,
    philhealth          NUMBER(10,2)   DEFAULT 0 NOT NULL,
    pagibig             NUMBER(10,2)   DEFAULT 0 NOT NULL,
    others              NUMBER(10,2)   DEFAULT 0 NOT NULL,
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    CONSTRAINT payroll_pk PRIMARY KEY (id),
    CONSTRAINT payroll_employee_id_uk UNIQUE (employee_id),
    CONSTRAINT payroll_daily_rate_ck CHECK (daily_rate > 0 AND daily_rate <= 100000),
    CONSTRAINT payroll_counts_ck CHECK (days_worked BETWEEN 0 AND 100 AND ot_hours BETWEEN 0 AND 100
        AND late_hours BETWEEN 0 AND 100 AND holiday_present BETWEEN 0 AND 100),
    CONSTRAINT payroll_holiday_type_ck CHECK (holiday_type IN ('Regular', 'Special'))
);

CREATE TABLE employee_shift (
    id                   NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    payroll_employee_id  VARCHAR2(50),
    names                VARCHAR2(100)  NOT NULL,
    schedule             VARCHAR2(100),
    breaks               VARCHAR2(100),
    duties               VARCHAR2(200),
    day_off              VARCHAR2(20),
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    CONSTRAINT employee_shift_pk PRIMARY KEY (id),
    CONSTRAINT employee_shift_day_off_ck CHECK (day_off IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
    CONSTRAINT employee_shift_payroll_fk FOREIGN KEY (payroll_employee_id)
        REFERENCES payroll (employee_id) ON DELETE SET NULL
);

CREATE TABLE users (
    id                    NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    username              VARCHAR2(50)   NOT NULL,
    password_hash         VARCHAR2(255)  NOT NULL,
    role                  VARCHAR2(20)   DEFAULT 'employee' NOT NULL,
    employee_id           VARCHAR2(50),
    must_change_password  NUMBER(1)      DEFAULT 0 NOT NULL,
    created_at            TIMESTAMP,
    updated_at            TIMESTAMP,
    CONSTRAINT users_pk PRIMARY KEY (id),
    CONSTRAINT users_username_uk UNIQUE (username),
    CONSTRAINT users_employee_id_uk UNIQUE (employee_id),
    CONSTRAINT users_role_ck CHECK (role IN ('admin', 'employee')),
    CONSTRAINT users_must_change_ck CHECK (must_change_password IN (0, 1)),
    CONSTRAINT users_payroll_fk FOREIGN KEY (employee_id)
        REFERENCES payroll (employee_id) ON DELETE CASCADE
);

-- Descriptions (Data Modeler shows these as the entity and attribute comments)
COMMENT ON TABLE inventory IS 'Product sold or used by the coffee shop, with its stock level';
COMMENT ON TABLE payroll IS 'Employee and their pay for the current pay period; employee_id (e.g. F-007) is the business key';
COMMENT ON TABLE employee_shift IS 'An employee''s shift on the schedule, with breaks, duties and requested day off';
COMMENT ON TABLE users IS 'Login account: the administrator, or one employee (signs in with their Employee ID)';

COMMENT ON COLUMN inventory.product_id IS 'Product number (primary key)';
COMMENT ON COLUMN inventory.category IS 'One of the fixed product categories';
COMMENT ON COLUMN inventory.quantity IS 'Units on hand (0 to 1000)';
COMMENT ON COLUMN inventory.image_path IS 'Uploaded image, under uploads/products';
COMMENT ON COLUMN payroll.employee_id IS 'Employee ID such as F-007; also the employee''s login name';
COMMENT ON COLUMN payroll.daily_rate IS 'Pay per day worked (default 550 pesos)';
COMMENT ON COLUMN payroll.holiday_type IS 'Regular or Special holiday rate';
COMMENT ON COLUMN payroll.net_pay IS 'Gross pay minus total deductions (computed by PayrollCalculator)';
COMMENT ON COLUMN employee_shift.payroll_employee_id IS 'Employee this shift belongs to (foreign key to payroll.employee_id)';
COMMENT ON COLUMN employee_shift.day_off IS 'Requested day off; no two employees share a day';
COMMENT ON COLUMN users.password_hash IS 'bcrypt hash; the password itself is never stored';
COMMENT ON COLUMN users.role IS 'admin or employee';
COMMENT ON COLUMN users.employee_id IS 'Employee this login belongs to (empty for the admin)';
COMMENT ON COLUMN users.must_change_password IS '1 while the account still uses a starting password';
